"""Separate classifier development, held-out evaluation and approved scaling.

There is no automatic transition between these phases. Human annotations and
acceptance are inputs, never generated by the model being evaluated.
"""
import json
from datetime import datetime, timezone
from pathlib import Path
import pandas as pd

if __package__:
    from .review import require_review, review_inputs, valid_reviewers, sha
    from .provenance import checkpoint_guard, fingerprint
    from .sampling import read_selected
else:
    from review import require_review, review_inputs, valid_reviewers, sha
    from provenance import checkpoint_guard, fingerprint
    from sampling import read_selected


def write_json(path, value):
    Path(path).write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def read_annotations(path, cfg, target, phase=None):
    frame = pd.read_csv(path, dtype=str, keep_default_na=False)
    required = {"post_id", "tweet", "human_label"}
    if not required <= set(frame) or frame.empty:
        raise ValueError("Human annotations need nonempty post_id, tweet and human_label columns.")
    if frame.post_id.duplicated().any():
        raise ValueError("Annotation IDs are duplicated.")
    labels = set(cfg.themes + [cfg.none_label])
    if not set(frame.human_label) <= labels:
        raise ValueError("Complete all human labels using the approved taxonomy.")
    for row in frame.to_dict("records"):
        if row["post_id"] not in target or row["tweet"] != target[row["post_id"]]["tweet"]:
            raise ValueError("Annotation text/ID does not match the declared target corpus.")
    record_path = Path(str(path) + ".review.json")
    if not record_path.exists():
        raise ValueError("Annotations require an actual human-labeling attestation (.review.json).")
    record = json.loads(record_path.read_text(encoding="utf-8"))
    if record.get("annotation_kind") != "human" or record.get("annotations_sha256") != sha(path) or not valid_reviewers(record.get("reviewers")):
        raise ValueError("Annotation attestation is missing, stale or not an actual human review.")
    if record.get('codebook_sha256') != sha(cfg.codebook_path):
        raise ValueError('Annotation review is stale: the codebook does not match.')
    if cfg.annotation_manifest:
        manifest = json.loads(Path(cfg.annotation_manifest).read_text(encoding='utf-8'))
        expected = manifest['packets'][phase]['ids']
        if len(expected) != len(set(expected)) or set(frame.post_id) != set(expected):
            raise ValueError('Annotation IDs differ from the frozen sampling manifest.')
    independent_columns = {'reviewer_1', 'reviewer_2', 'reviewer_1_label', 'reviewer_2_label'}
    if cfg.require_disjoint_windows and not independent_columns <= set(frame):
        raise ValueError('Retain both independent human annotations and reviewer names for the transfer study.')
    if {'reviewer_1_label','reviewer_2_label'} <= set(frame):
        if any(not set(frame[column]) <= labels for column in ['reviewer_1_label','reviewer_2_label']):
            raise ValueError('Independent annotations contain unknown labels.')
        disagreements=frame.reviewer_1_label != frame.reviewer_2_label
        if disagreements.any() and ('adjudication_note' not in frame or frame.loc[disagreements,'adjudication_note'].str.strip().eq('').any()):
            raise ValueError('Document actual adjudication of reviewer disagreements.')
    if {'reviewer_1', 'reviewer_2'} <= set(frame):
        expected_reviewers = {name.strip().casefold() for name in record['reviewers']}
        if any({row.reviewer_1.strip().casefold(), row.reviewer_2.strip().casefold()} != expected_reviewers for row in frame.itertuples()):
            raise ValueError('Independent reviewer names differ from the annotation attestation.')
    return frame


def record_annotation_review(path, reviewers, cfg=None):
    if not valid_reviewers(reviewers):
        raise ValueError("Record the actual researchers who labeled and reviewed these annotations.")
    write_json(str(path) + ".review.json", {
        "annotation_kind": "human", "annotations_sha256": sha(path), "reviewers": reviewers,
        "codebook_sha256": sha(cfg.codebook_path) if cfg and cfg.codebook_path else None,
        "recorded_at": datetime.now(timezone.utc).isoformat(),
    })


def validation_spec(cfg):
    if __package__:
        from .stage4_classification import build_prompt, SYSTEM
    else:
        from stage4_classification import build_prompt, SYSTEM
    return {"review": review_inputs(cfg), "model": cfg.llm_model, "backend": cfg.llm_backend,
            "system": SYSTEM, "prompt": build_prompt("{document}", cfg),
            "temperature": cfg.classify_temperature, "max_tokens": cfg.classify_max_tokens,
            "threshold": cfg.agreement_threshold, "parser_version": 3,
            "format_attempts": cfg.max_retries, "transport_attempts": cfg.max_retries,
            "development_sha256": sha(cfg.development_csv),
            "sampling_manifest_sha256": sha(cfg.annotation_manifest) if cfg.annotation_manifest else None}


def record_validation_review(cfg, reviewers):
    require_review(cfg)
    if not valid_reviewers(reviewers):
        raise ValueError("Record the actual researchers accepting classifier performance.")
    root = Path(cfg.output_dir, "stage4")
    report = json.loads((root / "validation_report.json").read_text(encoding="utf-8"))
    selection = json.loads((root / "classifier_selection.json").read_text(encoding="utf-8"))
    if not report.get("gate_passed") or selection["specification"] != validation_spec(cfg):
        raise ValueError("A current passing held-out evaluation is required.")
    if report["benchmark_sha256"] != sha(cfg.benchmark_csv):
        raise ValueError("Evaluation annotations changed after scoring.")
    write_json(root / "validation_review.json", {
        "decision": "approved", "human_review_performed": True, "reviewers": reviewers,
        "validation_report_sha256": sha(root / "validation_report.json"),
        "classifier_selection_sha256": sha(root / "classifier_selection.json"),
        "recorded_at": datetime.now(timezone.utc).isoformat(),
    })


def require_validation_review(cfg):
    root = Path(cfg.output_dir, "stage4")
    path = root / "validation_review.json"
    if not path.exists():
        raise ValueError("Researchers must inspect and approve held-out performance before corpus classification.")
    record = json.loads(path.read_text(encoding="utf-8"))
    selection = json.loads((root / "classifier_selection.json").read_text(encoding="utf-8"))
    if selection["specification"] != validation_spec(cfg):
        raise ValueError("Classifier acceptance is stale: analysis settings or research evidence changed.")
    report=json.loads((root / "validation_report.json").read_text(encoding="utf-8"))
    if report.get('benchmark_sha256')!=sha(cfg.benchmark_csv):
        raise ValueError('Classifier acceptance is stale: evaluation annotations changed.')
    if not (record.get("decision") == "approved" and record.get("human_review_performed") is True
            and valid_reviewers(record.get("reviewers"))
            and record.get("validation_report_sha256") == sha(root / "validation_report.json")
            and record.get("classifier_selection_sha256") == sha(root / "classifier_selection.json")):
        raise ValueError("Classifier acceptance is stale or incomplete.")
    return record


def run_validated_stage4(cfg):
    if __package__:
        from .stage4_classification import build_theme_dictionaries, build_option_list, boolean_classify, classify_text, classify_corpus, score_labels, is_blank
        from .llm_backend import make_backend
    else:
        from stage4_classification import build_theme_dictionaries, build_option_list, boolean_classify, classify_text, classify_corpus, score_labels, is_blank
        from llm_backend import make_backend
    if not cfg.themes or len(set(cfg.themes)) != len(cfg.themes) or any(not t.strip() for t in cfg.themes):
        raise ValueError("Supply unique, nonempty researcher-approved themes before Stage 4.")
    require_review(cfg)
    if not cfg.codebook_path:
        raise ValueError("A frozen codebook is required for held-out validation.")
    selected, sampling = read_selected(cfg, "target")
    if cfg.require_disjoint_windows and not cfg.annotation_manifest:
        raise ValueError('The transfer study requires a frozen annotation sampling manifest.')
    if cfg.annotation_manifest:
        manifest = json.loads(Path(cfg.annotation_manifest).read_text(encoding='utf-8'))
        if manifest.get('sampling') != sampling:
            raise ValueError('Annotation sampling manifest does not match the declared target population.')
    target = {row["post_id"]: row for row in selected}
    if any(is_blank(row["tweet"]) for row in selected):
        raise ValueError("Resolve missing target text before classification.")
    development = read_annotations(cfg.development_csv, cfg, target, 'development')
    root = Path(cfg.output_dir, "stage4")
    root.mkdir(parents=True, exist_ok=True)
    spec = validation_spec(cfg)
    checkpoint_guard(root / "evaluation_manifest.json", spec)
    write_json(root / "target_selection.json", sampling)
    labels = build_option_list(cfg)
    dictionaries = build_theme_dictionaries(cfg)
    action = cfg.stage4_action
    if action not in ("development", "validate", "classify"):
        raise ValueError("Stage 4 action must be development, validate or classify.")
    selection_path = root / "classifier_selection.json"
    selection = None
    if action != "development":
        if not selection_path.exists():
            raise ValueError("Select the classifier on development data before opening held-out evaluation.")
        selection = json.loads(selection_path.read_text(encoding="utf-8"))
        if selection["specification"] != spec:
            raise ValueError("Classifier selection is stale. Do not tune against an opened holdout.")
    evaluation = None
    if action in ("validate", "classify"):
        evaluation = read_annotations(cfg.benchmark_csv, cfg, target, 'evaluation')
        # Distinct IDs with repeated text are not independent evaluation examples.
        if set(development.post_id) & set(evaluation.post_id) or set(development.tweet) & set(evaluation.tweet):
            raise ValueError("Development and evaluation overlap by ID or exact text.")
    if action == "classify":
        if cfg.demonstration_exception_path:
            if __package__:from .demonstration import require_demonstration_exception
            else:from demonstration import require_demonstration_exception
            require_demonstration_exception(cfg)
            print('[stage4] Explicit demonstration exception: outputs remain UNVALIDATED model-assigned shares.')
        else:
            require_validation_review(cfg)
            report = json.loads((root / "validation_report.json").read_text(encoding="utf-8"))
            if not report["gate_passed"] or report["benchmark_sha256"] != sha(cfg.benchmark_csv):
                raise ValueError("A passing current evaluation is required before scaling.")

    needs_llm = action == "development" or selection["winner"] == "llm"
    backend = make_backend(cfg) if needs_llm else None
    try:
        if action in ("development", "validate"):
            frame = development.copy() if action == "development" else evaluation.copy()
            classifiers = ["llm", "boolean"] if action == "development" and dictionaries else ["llm"] if action == "development" else [selection["winner"]]
            if "llm" in classifiers:
                results = [classify_text(backend, row.tweet, cfg, request_key=f"{action}:{row.post_id}") for row in frame.itertuples()]
                frame["llm_pred"] = [r[0] for r in results]
                frame["llm_status"] = [r[1] for r in results]
                frame["llm_raw_response"] = [r[2] for r in results]
            if "boolean" in classifiers:
                frame["boolean_pred"] = frame.tweet.map(lambda text: boolean_classify(text, dictionaries, cfg))
            frame.to_csv(root / f"{action}_predictions.csv", index=False)
            if "llm" in classifiers and not frame.llm_status.eq("matched").all():
                raise RuntimeError("Unresolved benchmark calls: inspect preserved raw responses before scoring.")
            scores = {name: score_labels(frame.human_label, frame[f"{name}_pred"], labels) for name in classifiers}
            if action == "development":
                winner = max(scores, key=lambda name: scores[name]["agreement"])
                selection = {"winner": winner, "specification": spec, "development_scores": scores,
                             "selected_at": datetime.now(timezone.utc).isoformat(),
                             "selection_rule": "highest development agreement; LLM wins a tie"}
                # Preserve the exact pre-holdout choice on repeated cached invocations.
                if not selection_path.exists():
                    write_json(selection_path, selection)
                print(f"[stage4] Development selected {winner}. STOP: complete independent held-out annotation and run validate.")
            else:
                metrics = scores[selection["winner"]]
                unsupported = [t for t in cfg.themes if metrics["per_label"][t]["human_n"] == 0 or metrics["per_label"][t]["recall"] == 0]
                report = {"n_benchmark": len(frame), "winner": selection["winner"], "metrics": metrics,
                          "unsupported_themes": unsupported, "threshold": cfg.agreement_threshold,
                          "gate_passed": metrics["agreement"] > cfg.agreement_threshold and not unsupported,
                          "benchmark_sha256": sha(cfg.benchmark_csv), "specification_sha256": fingerprint(spec),
                          "human_review_performed": True,
                          "acceptance_status_at_evaluation": "Awaiting actual researcher acceptance; a later decision is retained in validation_review.json."}
                if {'reviewer_1_label','reviewer_2_label'} <= set(frame):
                    agreement=score_labels(frame.reviewer_1_label,frame.reviewer_2_label,labels)
                    report['independent_human_agreement']={k:agreement[k] for k in ['agreement','cohens_kappa','confusion']}
                    report['adjudicated_disagreements']=int((frame.reviewer_1_label!=frame.reviewer_2_label).sum())
                write_json(root / "validation_report.json", report)
                write_json(root / "benchmark_report.json", report)
                print(f"[stage4] Held-out agreement {metrics['agreement']:.1%}. STOP: researchers must inspect and accept performance.")
                if not report["gate_passed"]:
                    raise RuntimeError("Held-out evaluation failed. Do not scale; declare revisions and obtain a fresh evaluation sample.")
        else:
            corpus = pd.DataFrame(selected)
            if selection["winner"] == "llm":
                corpus = classify_corpus(backend, corpus, str(root), cfg)
                corpus["classifier"] = f"llm:{backend.model_id}"
            else:
                corpus["theme"] = corpus.tweet.map(lambda text: boolean_classify(text, dictionaries, cfg))
                corpus["status"] = "boolean"
                corpus["classifier"] = "boolean"
            corpus.to_csv(root / "classified_corpus.csv", index=False)
            if corpus.status.isin(["error", "unmatched", "empty"]).any():
                raise RuntimeError("Unresolved target classifications remain; inference is blocked.")
            write_json(root/'classification_status.json',{'classifier_validated':not bool(cfg.demonstration_exception_path),
                'mode':'unvalidated-demonstration' if cfg.demonstration_exception_path else 'accepted-research',
                'classified_corpus_sha256':sha(root/'classified_corpus.csv'),
                'demonstration_exception_sha256':sha(cfg.demonstration_exception_path) if cfg.demonstration_exception_path else None})
            print(f"[stage4] Classified the declared target corpus ({len(corpus):,} posts).")
    finally:
        if backend and backend.budget:
            backend.budget.export()
    return str(root)
